export function getWeaponsByType(type: string) {
  if (type === "Swords") {
    return swordsList;
  }
  if (type === "Broadblades") {
    return broadbladesList;
  }
  if (type === "Rectifiers") {
    return rectifiersList;
  }
  if (type === "Pistols") {
    return pistolsList;
  }
  if (type === "Gauntlets") {
    return gauntletsList;
  }
  return [];
}

/**
 * Human labels for the `mainStat` carried on every registry entry above (the
 * stat a weapon's secondary line grants, e.g. Crit Rate). Kept next to the
 * data it labels so adding a weapon with a new stat type surfaces both edits
 * in one place; `tests/weapons/weaponsRegistry.test.ts` fails if the registry
 * ever uses a key that isn't listed here.
 */
export const WEAPON_MAIN_STAT_LABELS: Record<string, string> = {
  ATK: "ATK",
  CritDMG: "Crit DMG",
  CritRate: "Crit Rate",
  DEF: "DEF",
  EnergyRegen: "Energy Regen",
  HP: "HP",
};

export function getWeaponMainStatLabel(mainStat: string): string {
  return WEAPON_MAIN_STAT_LABELS[mainStat] ?? mainStat;
}

async function loadModule(type: string, weaponName: string) {
  try {
    const module = await import(`@/weapons/${type}/${weaponName}.ts`);
    return module.getWeapon();
  } catch (error) {
    // console.error("Error loading weapon");
  }
}

export async function getWeaponByName(type: string, weaponName: string) {
  try {
    const weaponData = await loadModule(type, weaponName);
    return weaponData;
  } catch (error) {
    // throw "Unable to find weapon";
  }
}
